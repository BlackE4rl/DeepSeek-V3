CAVEATS = """\
## Caveats -- read these before believing any number above

1. **A good-looking backtest is the null result, not the finding.** Trend
   following on mega-cap technology over the last fifteen years mostly measures
   the fact that mega-cap technology went up a great deal. The only question
   worth answering is whether these rules beat simply owning the index, after
   costs, after tax, and out of sample. That is why the buy-and-hold comparison
   is the first table in this document.
2. **Survivorship and hindsight bias in the universe.** The mega-cap list was
   assembled knowing which companies won. `configs/universe_2010.yaml` exists to
   measure the size of that bias: run the identical strategy on it and compare.
   If the 2010 universe does materially worse, the mega-cap result is largely
   stock-picking hindsight rather than strategy edge, and the honest expectation
   for live trading sits closer to the 2010 number.
3. **Taxes are not modelled at all.** German Abgeltungsteuer of 25 % plus
   Solidaritatszuschlag, and possibly church tax, falls on every realized gain,
   against a EUR 1,000 Sparerpauschbetrag. A high-turnover strategy pays that
   bill every year while buy and hold defers it indefinitely. An edge of two
   percentage points a year before tax can be a deficit after it.
4. **Currency risk is unhedged and material.** A euro account holding dollar
   stocks earns part of its return from the euro-dollar rate. The per-currency
   attribution table separates the two so a currency tailwind is not mistaken
   for skill.
5. **Stop fills are optimistic.** Daily bars cannot reproduce the intraday path.
   A gap through the stop is filled at the open here, which is conservative for
   gaps, but nothing in this model reproduces February 2018, March 2020, or a
   single-name earnings gap. Look at the cost stress test at two and four times
   the modelled friction before believing anything.
6. **Parameter selection contaminates the evaluation.** Walk-forward reduces
   this but cannot remove it: the *rules themselves* -- a twenty-day pullback
   inside a long uptrend, on technology stocks -- were chosen by a human who
   already knows how the last fifteen years went. No in-sample/out-of-sample
   split can measure that kind of overfitting.
7. **The sample is small.** A few hundred trades gives a large standard error on
   Sharpe and Calmar. Quote the bootstrap band, never the point estimate.
8. **Scope limits.** Long only, no leverage, no shorting, no options, no
   intraday data, a single-currency cash ledger, and no delisted or acquired
   companies in the universe.
9. **This is not financial advice.** And a backtest is not even past
   performance: it is a simulation of a decision rule that nobody actually
   followed.
"""

