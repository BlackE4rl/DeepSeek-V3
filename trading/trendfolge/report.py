"""Markdown report assembly.

Three things are non-negotiable in every report this module produces:

* the comparison against buy and hold is the headline table, not an appendix;
* the caveats are appended automatically and cannot be switched off;
* the configuration hash and the data provenance are printed at the top, so any
  number in the document can be traced back to the exact inputs that made it.
"""

